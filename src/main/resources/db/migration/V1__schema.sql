CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL,
    senha_hash VARCHAR(100) NOT NULL,
    perfil VARCHAR(20) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_perfil CHECK (perfil IN ('CLIENTE', 'ADMIN'))
);

CREATE TABLE endereco (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    logradouro VARCHAR(160) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    complemento VARCHAR(100),
    bairro VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    uf CHAR(2) NOT NULL,
    cep VARCHAR(9) NOT NULL,
    CONSTRAINT fk_endereco_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    CONSTRAINT uk_categoria_nome UNIQUE (nome)
);

CREATE TABLE produto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    nome VARCHAR(160) NOT NULL,
    descricao TEXT NOT NULL,
    preco_base NUMERIC(10, 2) NOT NULL,
    imagem_url VARCHAR(1000),
    personalizavel BOOLEAN NOT NULL DEFAULT TRUE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_produto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT ck_produto_preco_base CHECK (preco_base >= 0)
);

CREATE TABLE opcao_personalizacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) NOT NULL,
    nome VARCHAR(100) NOT NULL,
    preco_adicional NUMERIC(10, 2) NOT NULL DEFAULT 0,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_opcao_tipo_nome UNIQUE (tipo, nome),
    CONSTRAINT ck_opcao_tipo CHECK (tipo IN ('MASSA', 'RECHEIO', 'COBERTURA', 'EXTRA')),
    CONSTRAINT ck_opcao_preco CHECK (preco_adicional >= 0)
);

CREATE TABLE carrinho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    CONSTRAINT uk_carrinho_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_carrinho_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id)
);

CREATE TABLE item_carrinho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrinho_id BIGINT NOT NULL,
    produto_id BIGINT NOT NULL,
    quantidade INTEGER NOT NULL,
    CONSTRAINT fk_item_carrinho_carrinho FOREIGN KEY (carrinho_id) REFERENCES carrinho (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_carrinho_produto FOREIGN KEY (produto_id) REFERENCES produto (id),
    CONSTRAINT ck_item_carrinho_quantidade CHECK (quantidade BETWEEN 1 AND 50)
);

CREATE TABLE item_carrinho_opcao (
    item_carrinho_id BIGINT NOT NULL,
    opcao_id BIGINT NOT NULL,
    PRIMARY KEY (item_carrinho_id, opcao_id),
    CONSTRAINT fk_item_carrinho_opcao_item FOREIGN KEY (item_carrinho_id) REFERENCES item_carrinho (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_carrinho_opcao_opcao FOREIGN KEY (opcao_id) REFERENCES opcao_personalizacao (id)
);

CREATE TABLE pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    endereco_snapshot TEXT,
    tipo_entrega VARCHAR(20) NOT NULL,
    taxa_entrega NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total NUMERIC(10, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id),
    CONSTRAINT ck_pedido_tipo_entrega CHECK (tipo_entrega IN ('ENTREGA', 'RETIRADA')),
    CONSTRAINT ck_pedido_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'EM_PREPARO', 'SAIU_PARA_ENTREGA', 'ENTREGUE', 'CANCELADO')),
    CONSTRAINT ck_pedido_taxa CHECK (taxa_entrega >= 0),
    CONSTRAINT ck_pedido_total CHECK (total >= 0)
);

CREATE TABLE item_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    nome_produto VARCHAR(160) NOT NULL,
    preco_unitario NUMERIC(10, 2) NOT NULL,
    quantidade INTEGER NOT NULL,
    opcoes_descricao TEXT NOT NULL,
    CONSTRAINT fk_item_pedido_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT ck_item_pedido_preco CHECK (preco_unitario >= 0),
    CONSTRAINT ck_item_pedido_quantidade CHECK (quantidade BETWEEN 1 AND 50)
);

CREATE TABLE pagamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    forma VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    valor NUMERIC(10, 2) NOT NULL,
    codigo_pix VARCHAR(255),
    CONSTRAINT uk_pagamento_pedido UNIQUE (pedido_id),
    CONSTRAINT fk_pagamento_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT ck_pagamento_forma CHECK (forma IN ('PIX', 'CARTAO', 'DINHEIRO')),
    CONSTRAINT ck_pagamento_status CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO')),
    CONSTRAINT ck_pagamento_valor CHECK (valor >= 0)
);

CREATE TABLE historico_status_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    autor VARCHAR(120) NOT NULL,
    CONSTRAINT fk_historico_pedido FOREIGN KEY (pedido_id) REFERENCES pedido (id) ON DELETE CASCADE,
    CONSTRAINT ck_historico_status CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'EM_PREPARO', 'SAIU_PARA_ENTREGA', 'ENTREGUE', 'CANCELADO'))
);

CREATE INDEX idx_endereco_usuario_id ON endereco (usuario_id);
CREATE INDEX idx_produto_nome ON produto (nome);
CREATE INDEX idx_produto_categoria_id ON produto (categoria_id);
CREATE INDEX idx_item_carrinho_carrinho_id ON item_carrinho (carrinho_id);
CREATE INDEX idx_item_carrinho_produto_id ON item_carrinho (produto_id);
CREATE INDEX idx_item_carrinho_opcao_opcao_id ON item_carrinho_opcao (opcao_id);
CREATE INDEX idx_pedido_usuario_criado_em ON pedido (usuario_id, criado_em DESC);
CREATE INDEX idx_item_pedido_pedido_id ON item_pedido (pedido_id);
CREATE INDEX idx_historico_pedido_em ON historico_status_pedido (pedido_id, em);